declare(strict_types=1);

namespace PhpOffice\PhpDatabase;

use InvalidArgumentException;

/**
 * Foreign key (Access: relationship) from columns of a table to columns of another table.
 */
class ForeignKey
{
    public const NO_ACTION = 'NO ACTION';
    public const CASCADE = 'CASCADE';
    public const SET_NULL = 'SET NULL';
    public const SET_DEFAULT = 'SET DEFAULT';
    public const RESTRICT = 'RESTRICT';

    /**
     * @var string
     */
    protected $name;

    /**
     * @var array<int, string>
     */
    protected $columns;

    /**
     * @var string
     */
    protected $referencedTable;

    /**
     * @var array<int, string>
     */
    protected $referencedColumns;

    /**
     * @var string
     */
    protected $onDelete = self::NO_ACTION;

    /**
     * @var string
     */
    protected $onUpdate = self::NO_ACTION;

    /**
     * @param array<int, string> $columns
     * @param array<int, string> $referencedColumns
     */
    public function __construct(string $name, array $columns, string $referencedTable, array $referencedColumns)
    {
        if (empty($columns) || count($columns) !== count($referencedColumns)) {
            throw new InvalidArgumentException(sprintf('The foreign key "%s" must have the same number of columns on both sides', $name));
        }
        $this->name = $name;
        $this->columns = array_values($columns);
        $this->referencedTable = $referencedTable;
        $this->referencedColumns = array_values($referencedColumns);
    }

    /**
     * Name of the constraint (may be empty: a name is then generated by the writers which need one).
     */
    public function getName(): string
    {
        return $this->name;
    }

    public function setName(string $name): self
    {
        $this->name = $name;

        return $this;
    }

    /**
     * @return array<int, string>
     */
    public function getColumns(): array
    {
        return $this->columns;
    }

    public function getReferencedTable(): string
    {
        return $this->referencedTable;
    }

    /**
     * @return array<int, string>
     */
    public function getReferencedColumns(): array
    {
        return $this->referencedColumns;
    }

    public function getOnDelete(): string
    {
        return $this->onDelete;
    }

    public function setOnDelete(string $action): self
    {
        $this->onDelete = self::checkAction($action);

        return $this;
    }

    public function getOnUpdate(): string
    {
        return $this->onUpdate;
    }

    public function setOnUpdate(string $action): self
    {
        $this->onUpdate = self::checkAction($action);

        return $this;
    }

    private static function checkAction(string $action): string
    {
        $action = strtoupper(trim((string) preg_replace('/\s+/', ' ', $action)));
        if (!in_array($action, [self::NO_ACTION, self::CASCADE, self::SET_NULL, self::SET_DEFAULT, self::RESTRICT], true)) {
            throw new InvalidArgumentException(sprintf('Unknown referential action "%s"', $action));
        }

        return $action;
    }
}
