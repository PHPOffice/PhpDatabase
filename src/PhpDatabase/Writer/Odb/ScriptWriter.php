declare(strict_types=1);

namespace PhpOffice\PhpDatabase\Writer\Odb;

use DateTimeImmutable;
use PhpOffice\PhpDatabase\Column;
use PhpOffice\PhpDatabase\ColumnType;
use PhpOffice\PhpDatabase\Database;
use PhpOffice\PhpDatabase\Exception\WriterException;
use PhpOffice\PhpDatabase\Expression;
use PhpOffice\PhpDatabase\ForeignKey;
use PhpOffice\PhpDatabase\Shared\Sql\Dialect;
use PhpOffice\PhpDatabase\Shared\Sql\TypeMapper;
use PhpOffice\PhpDatabase\Table;

/**
 * Writer of an HSQLDB 1.8 database as embedded in ODB files: tables are written as MEMORY tables,
 * their rows being INSERT statements of the script.
 */
class ScriptWriter
{
    /**
     * Objects skipped by the last getScript().
     *
     * @var array<int, string>
     */
    private $warnings = [];

    /**
     * Names of the tables, views and columns by lower case name (to fix the case of the identifiers of views).
     *
     * @var array<string, string>
     */
    private $names = [];

    /**
     * @return array<int, string>
     */
    public function getWarnings(): array
    {
        return $this->warnings;
    }

    public function getScript(Database $database): string
    {
        $lines = ['CREATE SCHEMA PUBLIC AUTHORIZATION DBA'];
        $restarts = [];
        $constraints = [];
        $this->warnings = [];
        $this->names = [];
        foreach ($database->getTables() as $table) {
            $this->names[strtolower($table->getName())] = $table->getName();
            foreach ($table->getColumns() as $column) {
                $this->names[strtolower($column->getName())] ??= $column->getName();
            }
        }
        foreach ($database->getTables() as $table) {
            $identity = $this->getIdentityColumn($table);
            $definitions = [];
            foreach ($table->getColumns() as $column) {
                $definition = self::quoteIdentifier($column->getName()) . ' ' . $this->getType($table, $column);
                $default = $column->getDefaultValue();
                if ($column === $identity) {
                    $definition .= ' GENERATED BY DEFAULT AS IDENTITY(START WITH 0)';
                } elseif ($default instanceof Expression) {
                    if ($default->isCurrentDateTime()) {
                        $definition .= ' DEFAULT ' . $default->getSql();
                    } else {
                        $this->warnings[] = sprintf('Default value of the column "%s" of the table "%s" not written: expression', $column->getName(), $table->getName());
                    }
                } elseif (null !== $default) {
                    $definition .= ' DEFAULT ' . self::literal($column, $default);
                }
                if (!$column->isNullable() || $column->isPrimaryKey()) {
                    $definition .= ' NOT NULL';
                }
                if ($column === $identity && $column->isPrimaryKey()) {
                    $definition .= ' PRIMARY KEY';
                }
                $definitions[] = $definition;
            }
            $primary = $table->getPrimaryKeyColumns();
            if (!empty($primary) && (null === $identity || !$identity->isPrimaryKey())) {
                $definitions[] = 'PRIMARY KEY(' . implode(',', array_map(static fn (Column $column): string => self::quoteIdentifier($column->getName()), $primary)) . ')';
            }
            foreach ($table->getChecks() as $check) {
                $expression = $this->convert($check->getExpression());
                $problem = Dialect::checkHsqldb($expression);
                if (null !== $problem) {
                    $this->warnings[] = sprintf('Check constraint of the table "%s" not written: %s', $table->getName(), $problem);

                    continue;
                }
                $definitions[] = ('' !== $check->getName() ? 'CONSTRAINT ' . self::quoteIdentifier($check->getName()) . ' ' : '') . 'CHECK(' . self::escape($expression) . ')';
            }
            $lines[] = 'CREATE MEMORY TABLE ' . self::quoteIdentifier($table->getName()) . '(' . implode(',', $definitions) . ')';
            foreach ($table->getIndexes() as $index) {
                if ($index->hasExpressions() || null !== $index->getWhere()) {
                    $this->warnings[] = sprintf('Index "%s" of the table "%s" not written: indexes on expressions and partial indexes are not supported by HSQLDB', $index->getName(), $table->getName());

                    continue;
                }
                if ($index->isUnique()) {
                    self::checkUnique($table, $index->getColumns(), $index->getName());
                }
                $lines[] = 'CREATE ' . ($index->isUnique() ? 'UNIQUE ' : '') . 'INDEX ' . self::quoteIdentifier($index->getName())
                    . ' ON ' . self::quoteIdentifier($table->getName()) . '(' . self::columnList($index->getColumns()) . ')';
            }
            foreach ($table->getForeignKeys() as $foreignKey) {
                $referenced = $database->getTable($foreignKey->getReferencedTable());
                if (null === $referenced || !$referenced->isUniqueKey($foreignKey->getReferencedColumns())) {
                    // HSQLDB requires a primary key or a unique constraint on the referenced columns
                    $this->warnings[] = sprintf('Foreign key of the table "%s" not written: the referenced columns are not unique', $table->getName());

                    continue;
                }
                $constraint = 'ALTER TABLE ' . self::quoteIdentifier($table->getName()) . ' ADD';
                if ('' !== $foreignKey->getName()) {
                    $constraint .= ' CONSTRAINT ' . self::quoteIdentifier($foreignKey->getName());
                }
                $constraint .= ' FOREIGN KEY(' . self::columnList($foreignKey->getColumns()) . ') REFERENCES '
                    . self::quoteIdentifier($referenced->getName()) . '(' . self::columnList($foreignKey->getReferencedColumns()) . ')';
                foreach (['DELETE' => $foreignKey->getOnDelete(), 'UPDATE' => $foreignKey->getOnUpdate()] as $event => $action) {
                    if (ForeignKey::NO_ACTION !== $action && ForeignKey::RESTRICT !== $action) {
                        $constraint .= ' ON ' . $event . ' ' . $action;
                    }
                }
                $constraints[] = $constraint;
            }
            if (null !== $identity) {
                $restarts[] = 'ALTER TABLE ' . self::quoteIdentifier($table->getName()) . ' ALTER COLUMN ' . self::quoteIdentifier($identity->getName()) . ' RESTART WITH ' . $table->getNextAutoIncrement($identity);
            }
        }
        array_push($lines, ...$constraints);
        array_push($lines, ...$restarts);
        $known = array_map('strtolower', array_map(static fn (Table $table): string => $table->getName(), $database->getTables()));
        foreach ($database->getTriggers() as $trigger) {
            $this->warnings[] = sprintf('Trigger "%s" not written: only SQLite triggers are supported', $trigger->getName());
        }
        foreach ($database->getViews() as $view) {
            $sql = $this->convert($view->getSql());
            $problem = Dialect::isPortableSelect($view->getSql()) ? Dialect::checkHsqldb($sql) : 'unsupported SQL';
            if (null === $problem) {
                foreach (self::referencedTables($sql) as $name) {
                    if (!in_array(strtolower($name), $known, true)) {
                        $problem = sprintf('unknown table "%s"', $name);
                    }
                }
            }
            if (null !== $problem) {
                $this->warnings[] = sprintf('View "%s" not written: %s', $view->getName(), $problem);

                continue;
            }
            $lines[] = 'CREATE VIEW ' . self::quoteIdentifier($view->getName()) . ' AS ' . self::escape($sql);
            $known[] = strtolower($view->getName());
            $this->names[strtolower($view->getName())] = $view->getName();
        }
        array_push($lines, 'CREATE USER SA PASSWORD ""', 'GRANT DBA TO SA', 'SET WRITE_DELAY 60', 'SET SCHEMA PUBLIC');
        foreach ($database->getTables() as $table) {
            $prefix = 'INSERT INTO ' . self::quoteIdentifier($table->getName()) . ' VALUES(';
            foreach ($table->getRows() as $row) {
                $values = [];
                foreach ($table->getColumns() as $column) {
                    $values[] = self::literal($column, $row[$column->getName()]);
                }
                $lines[] = $prefix . implode(',', $values) . ')';
            }
        }

        return implode("\n", $lines) . "\n";
    }

    /**
     * HSQLDB refuses to open a script whose rows violate a unique index.
     *
     * @param array<int, string> $names
     */
    private static function checkUnique(Table $table, array $names, string $indexName): void
    {
        $keys = [];
        foreach ($table->getRows() as $row) {
            $entry = [];
            foreach ($names as $name) {
                $entry[] = $row[$name] ?? null;
            }
            if (in_array(null, $entry, true)) {
                continue;
            }
            $key = serialize($entry);
            if (isset($keys[$key])) {
                throw new WriterException(sprintf('Duplicate value in the unique index "%s" of the table "%s"', $indexName, $table->getName()));
            }
            $keys[$key] = true;
        }
    }

    /**
     * Standard SQL to HSQLDB, with the identifiers in the case of the tables/columns they name.
     */
    private function convert(string $sql): string
    {
        $tokens = Dialect::transform(Dialect::tokenize($sql, Dialect::STANDARD), Dialect::STANDARD, Dialect::HSQLDB);
        foreach ($tokens as $index => $token) {
            if (Dialect::T_IDENTIFIER === $token[0] && isset($this->names[strtolower($token[1])])) {
                $tokens[$index][1] = $this->names[strtolower($token[1])];
            }
        }

        return trim(Dialect::render($tokens, Dialect::HSQLDB));
    }

    /**
     * Tables named after FROM and JOIN in a statement.
     *
     * @return array<int, string>
     */
    private static function referencedTables(string $sql): array
    {
        $tokens = Dialect::tokenize($sql, Dialect::HSQLDB);
        $names = [];
        foreach ($tokens as $index => $token) {
            if (Dialect::is($token, 'FROM', 'JOIN') && Dialect::T_IDENTIFIER === ($tokens[$index + 1][0] ?? '')) {
                $next = $tokens[$index + 2] ?? ['', '', ''];
                $names[] = Dialect::is($next, '.') ? ($tokens[$index + 3][1] ?? '') : $tokens[$index + 1][1];
            }
        }

        return $names;
    }

    /**
     * @param array<int, string> $names
     */
    private static function columnList(array $names): string
    {
        return implode(',', array_map([self::class, 'quoteIdentifier'], $names));
    }

    public function getProperties(): string
    {
        return "#HSQL Database Engine 1.8.0.10\n"
            . '#' . gmdate('D M d H:i:s \G\M\T Y') . "\n"
            . "hsqldb.script_format=0\n"
            . "runtime.gc_interval=0\n"
            . "sql.enforce_strict_size=true\n"
            . "hsqldb.cache_size_scale=8\n"
            . "readonly=false\n"
            . "hsqldb.nio_data_file=false\n"
            . "hsqldb.cache_scale=13\n"
            . "version=1.8.0\n"
            . "hsqldb.default_table_type=cached\n"
            . "hsqldb.cache_file_scale=1\n"
            . "hsqldb.lock_file=true\n"
            . "hsqldb.log_size=10\n"
            . "modified=no\n"
            . "hsqldb.cache_version=1.7.0\n"
            . "hsqldb.original_version=1.8.0\n"
            . "hsqldb.compatible_version=1.8.0\n";
    }

    /**
     * HSQLDB allows one identity column: an auto-increment integer column being the primary key (or without primary key).
     */
    private function getIdentityColumn(Table $table): ?Column
    {
        $primary = $table->getPrimaryKeyColumns();
        foreach ($table->getColumns() as $column) {
            if (!$column->isAutoIncrement() || !in_array($column->getType(), [ColumnType::INTEGER, ColumnType::BIGINT], true)) {
                continue;
            }
            if (empty($primary) || (1 === count($primary) && $primary[0] === $column)) {
                return $column;
            }
        }

        return null;
    }

    private function getType(Table $table, Column $column): string
    {
        if (ColumnType::TEXT === $column->getType() && null === $column->getLength() && !TypeMapper::isComplex($column)) {
            // VARCHAR needs a size with sql.enforce_strict_size: the longest value (at least 255)
            $length = 255;
            foreach ($table->getRows() as $row) {
                $value = $row[$column->getName()];
                if (is_string($value)) {
                    $length = max($length, mb_strlen($value, 'UTF-8'));
                }
            }

            return sprintf('VARCHAR(%d)', $length);
        }

        return TypeMapper::toSqlType($column, true);
    }

    /**
     * SQL literal as written by HSQLDB in its scripts.
     */
    public static function literal(Column $column, mixed $value): string
    {
        if (null === $value) {
            return 'NULL';
        }
        if (TypeMapper::isComplex($column)) {
            return "'" . self::escape(str_replace("'", "''", (string) TypeMapper::flatten($column, $value))) . "'";
        }
        switch ($column->getType()) {
            case ColumnType::BOOLEAN:
                return $value ? 'TRUE' : 'FALSE';
            case ColumnType::TINYINT:
            case ColumnType::SMALLINT:
            case ColumnType::INTEGER:
            case ColumnType::BIGINT:
                return (string) (int) $value;
            case ColumnType::FLOAT:
            case ColumnType::DOUBLE:
                $float = (float) $value;
                if (is_nan($float) || is_infinite($float)) {
                    return 'NULL';
                }
                $string = (string) $float;

                return str_contains($string, 'E') || str_contains($string, '.') ? str_replace('E+', 'E', $string) : $string . 'E0';
            case ColumnType::DECIMAL:
                return (string) $value;
            case ColumnType::DATE:
            case ColumnType::TIME:
            case ColumnType::DATETIME:
                return "'" . self::formatDate($column, $value) . "'";
            case ColumnType::BLOB:
                return "'" . bin2hex((string) $value) . "'";
            default:
                return "'" . self::escape(str_replace("'", "''", (string) $value)) . "'";
        }
    }

    private static function formatDate(Column $column, mixed $value): string
    {
        if (!$value instanceof DateTimeImmutable) {
            return (string) $value;
        }
        switch ($column->getType()) {
            case ColumnType::DATE:
                return $value->format('Y-m-d');
            case ColumnType::TIME:
                return $value->format('H:i:s');
            default:
                return $value->format('Y-m-d H:i:s') . ('000000' !== $value->format('u') ? '.' . $value->format('u') : '.0');
        }
    }

    public static function quoteIdentifier(string $name): string
    {
        return '"' . self::escape(str_replace('"', '""', $name)) . '"';
    }

    /**
     * Escape like HSQLDB: characters outside of printable ASCII (and the backslash) as \uXXXX.
     */
    public static function escape(string $value): string
    {
        if (1 !== preg_match('/[^\x20-\x5b\x5d-\x7e]/', $value)) {
            return $value;
        }
        $utf16 = (string) mb_convert_encoding($value, 'UTF-16BE', 'UTF-8');
        $result = '';
        for ($i = 0, $length = strlen($utf16); $i < $length; $i += 2) {
            $unit = (ord($utf16[$i]) << 8) | ord($utf16[$i + 1]);
            $result .= ($unit >= 0x20 && $unit <= 0x7e && 0x5c !== $unit) ? chr($unit) : sprintf('\\u%04x', $unit);
        }

        return $result;
    }
}
